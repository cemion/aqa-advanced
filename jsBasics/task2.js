const greeting = 'Hello';
const name1 = 'Anna';
const name2 = 'Ivan';

// Concatenation
const concatGreeting = greeting + ' ' + name1 + '! ' + greeting + ' ' + name2 + '!';
console.log(concatGreeting);

// Template string
const templateGreeting = `${greeting} ${name1}! ${greeting} ${name2}!`;
console.log(templateGreeting);
